// stringer generates a String method for an integer type with constants, like
// golang.org/x/tools/cmd/stringer. It loads the package that declares the type
// with go/packages, which go_stringer points at gopackagesdriver.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/constant"
	"go/format"
	"go/token"
	"go/types"
	"log"
	"os"
	"sort"
	"strings"

	"golang.org/x/tools/go/packages"
)

func main() {
	typeName := flag.String("type", "", "name of the type to generate a String method for")
	output := flag.String("output", "", "path of the Go file to write")
	lineComment := flag.Bool("linecomment", false, "use the line comment of a constant as its name")
	flag.Parse()
	if *typeName == "" || *output == "" || flag.NArg() != 1 {
		log.Fatal("usage: stringer -type T -output file.go [-linecomment] importpath")
	}

	cfg := &packages.Config{
		Mode: packages.NeedName | packages.NeedTypes | packages.NeedTypesInfo | packages.NeedSyntax,
	}
	pkgs, err := packages.Load(cfg, flag.Arg(0))
	if err != nil {
		log.Fatal(err)
	}
	if packages.PrintErrors(pkgs) > 0 {
		os.Exit(1)
	}
	if len(pkgs) != 1 {
		log.Fatalf("expected one package for %s, got %d", flag.Arg(0), len(pkgs))
	}

	src, err := generate(pkgs[0], *typeName, *lineComment)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*output, src, 0o666); err != nil {
		log.Fatal(err)
	}
}

type value struct {
	name string
	val  constant.Value
	pos  token.Pos
}

func generate(pkg *packages.Package, typeName string, lineComment bool) ([]byte, error) {
	typ, ok := pkg.Types.Scope().Lookup(typeName).(*types.TypeName)
	if !ok {
		return nil, fmt.Errorf("%s.%s is not a type", pkg.PkgPath, typeName)
	}
	basic, ok := typ.Type().Underlying().(*types.Basic)
	if !ok || basic.Info()&types.IsInteger == 0 {
		return nil, fmt.Errorf("%s.%s is not an integer type", pkg.PkgPath, typeName)
	}

	var names map[*types.Const]string
	if lineComment {
		names = lineComments(pkg)
	}

	var values []value
	scope := pkg.Types.Scope()
	for _, name := range scope.Names() {
		c, ok := scope.Lookup(name).(*types.Const)
		if !ok || !types.Identical(c.Type(), typ.Type()) {
			continue
		}
		if comment, ok := names[c]; ok {
			name = comment
		}
		values = append(values, value{name: name, val: c.Val(), pos: c.Pos()})
	}
	if len(values) == 0 {
		return nil, fmt.Errorf("%s.%s has no constants", pkg.PkgPath, typeName)
	}

	// The first declared constant names a value shared by several constants.
	sort.Slice(values, func(i, j int) bool {
		if !constant.Compare(values[i].val, token.EQL, values[j].val) {
			return constant.Compare(values[i].val, token.LSS, values[j].val)
		}
		return values[i].pos < values[j].pos
	})

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by stringer; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\nimport \"strconv\"\n\n", pkg.Name)
	fmt.Fprintf(&b, "func (i %s) String() string {\n\tswitch i {\n", typeName)
	for i, v := range values {
		if i > 0 && constant.Compare(v.val, token.EQL, values[i-1].val) {
			continue
		}
		fmt.Fprintf(&b, "\tcase %s:\n\t\treturn %q\n", v.val.ExactString(), v.name)
	}
	fallback := "strconv.FormatInt(int64(i), 10)"
	if basic.Info()&types.IsUnsigned != 0 {
		fallback = "strconv.FormatUint(uint64(i), 10)"
	}
	fmt.Fprintf(&b, "\t}\n\treturn %q + %s + \")\"\n}\n", typeName+"(", fallback)
	return format.Source(b.Bytes())
}

// lineComments returns the line comments of the package's constants, which
// requires the syntax of the package in addition to its types.
func lineComments(pkg *packages.Package) map[*types.Const]string {
	comments := map[*types.Const]string{}
	for _, file := range pkg.Syntax {
		for _, decl := range file.Decls {
			gen, ok := decl.(*ast.GenDecl)
			if !ok || gen.Tok != token.CONST {
				continue
			}
			for _, spec := range gen.Specs {
				spec := spec.(*ast.ValueSpec)
				if spec.Comment == nil {
					continue
				}
				for _, ident := range spec.Names {
					if c, ok := pkg.TypesInfo.Defs[ident].(*types.Const); ok {
						comments[c] = strings.TrimSpace(spec.Comment.Text())
					}
				}
			}
		}
	}
	return comments
}
